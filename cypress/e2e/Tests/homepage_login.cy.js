import { faker } from '@faker-js/faker';

describe('OrangeHRM Login Test Suite', () => {

  // Test Case 1: Valid Login using actual credentials
  it('Should successfully log in with valid credentials', () => {
    cy.visit('https://opensource-demo.orangehrmlive.com/web/index.php/auth/login');
    
    // Enter valid credentials
    cy.get('input[name="username"]').type('Admin');
    cy.get('input[name="password"]').type('admin123');
    cy.get('button[type="submit"]').click();
    
    // Page verification assertions
    cy.url().should('include', '/dashboard');
    cy.get('.oxd-topbar-header-breadcrumb-module').should('contain', 'Dashboard');
    
    // Widget verification assertion
    cy.contains('.orangehrm-dashboard-widget-name', 'Time at Work').should('be.visible');
  });

  // Test Case 2: Invalid Login using dynamic Faker credentials
  it('Should fail login when using dynamic invalid credentials generated by Faker', () => {
    // Generate fresh fake data using modern Faker syntax (v8+)
    const randomUsername = faker.person.firstName();
    const randomPassword = faker.internet.password({ length: 12 });

    cy.visit('https://opensource-demo.orangehrmlive.com/web/index.php/auth/login');
    
    // Type generated fake credentials into input fields
    cy.get('input[name="username"]').type(randomUsername);
    cy.get('input[name="password"]').type(randomPassword);
    cy.get('button[type="submit"]').click();

    // Verify error message alert
    cy.get('.oxd-alert-content-text').should('contain', 'Invalid credentials');
  });

});